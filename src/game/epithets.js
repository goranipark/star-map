export const ALL_EPITHETS = EPITHET_GROUPS.flatMap((group) => group.items);

export function epithetGroupFor(epithet) {
  return EPITHET_GROUPS.find((group) => group.items.includes(epithet)) ?? null;
}

/** 직전 선택은 피해서 “다시 골라 줘”가 실제로 다른 제안을 하게 한다. */
export function randomEpithet(exclude = '') {
  const candidates = ALL_EPITHETS.filter((item) => item !== exclude);
  return candidates[Math.floor(Math.random() * candidates.length)];
}
